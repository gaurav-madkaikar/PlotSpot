"""Explicit content preparation independent of viewer requests.

Starter wording is curated, not generated by an autonomous agent. Compile it
against live Wikipedia or an explicitly chosen previously fetched source.
"""
import argparse
import asyncio
import json
from pathlib import Path
import httpx
from movie_companion.content_store import ContentStore, DEFAULT_PATH
from movie_companion.evidence_store import SourceDocument
from movie_companion.prepared_content import CONTENT_VERSION, compile_collection
from movie_companion.reviewed_content import CONTENT_VERSION as MULTI_VERSION, SUPPORTED_MOVIES
from movie_companion.wikipedia_source import fetch_movie_source


async def prepare(args):
    movie_id = getattr(args, "movie_id", 157336)
    if type(movie_id) is not int or movie_id not in SUPPORTED_MOVIES:
        raise ValueError("No reviewed content bank for this movie")
    store = ContentStore(args.database)
    saved = store.load(movie_id)
    if saved and not args.refresh:
        print(f"Existing collection retained ({saved['version']}); no source or model calls. Use --refresh to explicitly replace it.")
        write_report(args, movie_id=movie_id, state="retained", version=saved['version'], source_revision=saved['source_revision'])
        return
    print(f"Movie {movie_id}: reading source snapshot…")
    if args.source_snapshot:
        source = SourceDocument(**json.loads(Path(args.source_snapshot).read_text()))
    else:
        async with httpx.AsyncClient(base_url="https://en.wikipedia.org", timeout=30, trust_env=False, follow_redirects=False, headers={"User-Agent": "MovieCompanionLearning/0.1 (local educational source reader)"}) as client:
            source = await fetch_movie_source(client, movie_id=movie_id)
    if source.movie_id != movie_id:
        raise ValueError("Source snapshot belongs to a different movie")
    print(f"Movie {movie_id}: validating reviewed story and background evidence…")
    quiz, facts = compile_collection(source)
    version = CONTENT_VERSION if movie_id == 157336 else MULTI_VERSION
    # Refresh only the publication we originally read; preserve concurrent edits.
    store.publish(movie_id, version=version, source_revision=source.revision, quiz=quiz, facts=facts,
                  expected_prepared_at=saved['prepared_at'] if saved else None)
    scored = sum(q.kind != 'interpretation' for q in quiz.items)
    reflections = sum(q.kind == 'interpretation' for q in quiz.items)
    write_report(args, movie_id=movie_id, state="published", version=version, source_revision=source.revision,
                 source_ref=source.source_ref, facts=len(facts.items), scored_questions=scored, reflections=reflections,
                 method="authored-reviewed-bank", model_calls=0)
    print(f"Published {len(facts.items)} facts, {scored} scored questions and {reflections} unscored reflections; {source.revision}.")


def write_report(args, **result):
    report = getattr(args, "report", None)
    if report:
        report = Path(report)
        report.parent.mkdir(parents=True, exist_ok=True)
        report.write_text(json.dumps(result, indent=2) + '\n')


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-snapshot")
    parser.add_argument("--movie-id", type=int, choices=sorted(SUPPORTED_MOVIES), default=157336)
    parser.add_argument("--report", type=Path)
    parser.add_argument("--database", type=Path, default=DEFAULT_PATH)
    parser.add_argument("--refresh", action="store_true")
    asyncio.run(prepare(parser.parse_args()))
